function assemble_K(EToV, c, d,start, stop, n_elements)
    E = length(EToV)
    b = zeros(n_elements)
    k = ones(E)

    I = Int[]
    J = Int[]
    V = Float64[]

    for e in 1:E
        i, j = EToV[e]
        ke = float(k[e])

        push!(I, i); push!(J, i); push!(V,  ke)
        push!(I, j); push!(J, j); push!(V,  ke)
        push!(I, i); push!(J, j); push!(V, -ke)
        push!(I, j); push!(J, i); push!(V, -ke)
    end
    A =  sparse(I, J, V, n_elements, n_elements)
    # Algorithm 2
    ## NOTE: check if A[1, 2] is efficient
    b[start] = c
    b[stop] = d
    
    A[start, start:end] .= 0
    A[start, 1:start] .= 0

    A[stop, stop:end] .= 0
    A[stop, 1:stop] .= 0

    A[start, start] = 1
    A[stop, stop] = 1


    # Version 1
    return A, b, A \ b
end

