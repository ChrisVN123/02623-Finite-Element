function EToV_radius(nodes::AbstractVector, r::Real)
    n = length(nodes)
    r2 = r^2
    edges = Tuple{Int,Int}[]

    for i in 1:n-1
        xi, yi = nodes[i]
        for j in i+1:n
            xj, yj = nodes[j]
            if (xi - xj)^2 + (yi - yj)^2 ≤ r2
                push!(edges, (i, j))
            end
        end
    end
    return edges
end

